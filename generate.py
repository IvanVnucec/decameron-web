"""Build the decameron website into build/.

    python generate.py            build from data/ (downloads it first if missing)
    python generate.py --fetch    download the latest camera list, firmware and change log, then build
    python generate.py --watch    build, then serve build/ with live reload

The camera list and firmware come from the catchcam firmware repo, which rebuilds both
every night from OpenStreetMap. data/ is a local cache of those downloads and is not
committed; CI runs --fetch on every deploy so the site always matches the latest firmware.

Every FAQ question and answer lives in templates/_faq.html, and the facts the pages share
(price, contact email, warranty, ...) live in templates/_site.html.
"""
import argparse
import hashlib
import importlib
import json
import os
import re
import shutil
import sys
import urllib.parse
import urllib.request
from datetime import date, datetime, timezone
from pathlib import Path

from jinja2 import Environment, FileSystemLoader, select_autoescape

import mapimage

ROOT = Path(__file__).parent
TEMPLATES_DIR = ROOT / "templates"
BUILD_DIR = ROOT / "build"
DATA_DIR = ROOT / "data"
VIDEO_DIR = ROOT / "video"  # optional: video/demo.mp4 (+ demo.jpg poster) replaces the YouTube embed

UPSTREAM_REPO = "IvanVnucec/catchcam"
CAMS_HEADER_URL = f"https://raw.githubusercontent.com/{UPSTREAM_REPO}/master/src/cams/cams_list.h"
FIRMWARE_URL = f"https://github.com/{UPSTREAM_REPO}/releases/download/master/catchcam.uf2"
CHANGES_URL = f"https://api.github.com/repos/{UPSTREAM_REPO}/commits?path=src/cams/cams_list.h&per_page=10"

CAMS_HEADER = DATA_DIR / "cams_list.h"
FIRMWARE = DATA_DIR / "catchcam.uf2"
CHANGES = DATA_DIR / "changes.json"

# coastlines, lakes and borders for the static coverage map (Natural Earth, public domain)
NATURAL_EARTH_URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/{}.geojson"
LAND, LAKES, BORDERS = (DATA_DIR / f"{name}.geojson" for name in ("ne_50m_land", "ne_50m_lakes", "ne_50m_admin_0_boundary_lines_land"))
COVERAGE_IMAGE = DATA_DIR / "coverage-map.webp"

FIRMWARE_PUBLIC_NAME = "decameron.uf2"

PAGES = [
    "index.html",
    "how-it-works.html",
    "camera-coverage.html",
    "setup-and-update.html",
    "support-and-faq.html",
    "order.html",
    "about.html",
    "404.html",
]

# ---------------------------------------------------------------------------
# data: camera list, firmware, change log
# ---------------------------------------------------------------------------

CAM_LINE = re.compile(
    r"\{\s*(-?\d+(?:\.\d+)?)f,\s*(-?\d+(?:\.\d+)?)f,\s*(\d+)\s*\},\s*//\s*https://www\.openstreetmap\.org/node/(\d+)"
)
HEADER_DATE = re.compile(r"generated by a script on (\d{2})-(\d{2})-(\d{4})")


def http_get(url, accept=None):
    headers = {"User-Agent": "decameron-web-build"}
    if accept:
        headers["Accept"] = accept
    token = os.environ.get("GITHUB_TOKEN")
    if token and url.startswith("https://api.github.com/"):
        headers["Authorization"] = f"Bearer {token}"
    req = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(req, timeout=300) as response:
        return response.read()


def fetch_changes():
    """Per-day counts of cameras added, removed and updated, from the firmware repo's history."""
    days = {}
    for commit in json.loads(http_get(CHANGES_URL)):
        diff = http_get(commit["url"], accept="application/vnd.github.diff").decode("utf-8", "replace")
        plus, minus = set(), set()
        for line in diff.splitlines():
            if line[:1] in "+-":
                m = CAM_LINE.search(line)
                if m:
                    (plus if line[0] == "+" else minus).add(m.group(4))
        when = commit["commit"]["committer"]["date"]  # e.g. 2026-11-18T03:12:45Z
        day = days.setdefault(when[:10], {"time": when, "added": 0, "removed": 0, "updated": 0})
        day["time"] = max(day["time"], when)
        day["added"] += len(plus - minus)
        day["removed"] += len(minus - plus)
        day["updated"] += len(plus & minus)
    return [{"date": d, **v} for d, v in sorted(days.items(), reverse=True)]


def fetch():
    DATA_DIR.mkdir(exist_ok=True)
    print("downloading camera list...")
    CAMS_HEADER.write_bytes(http_get(CAMS_HEADER_URL))
    print("downloading firmware...")
    FIRMWARE.write_bytes(http_get(FIRMWARE_URL))
    print("downloading change log...")
    try:
        CHANGES.write_text(json.dumps(fetch_changes(), indent=1))
    except Exception as error:  # the change log is nice to have, never block a build on it
        print(f"  could not fetch change log: {error}")
        if not CHANGES.exists():
            CHANGES.write_text("[]")
    fetch_basemap()


def fetch_basemap():
    """Natural Earth barely changes, so it is downloaded once and kept in data/."""
    DATA_DIR.mkdir(exist_ok=True)
    for path in (LAND, LAKES, BORDERS):
        if not path.exists():
            print(f"downloading {path.name}...")
            path.write_bytes(http_get(NATURAL_EARTH_URL.format(path.stem)))


def coverage_image(cams):
    """The static world map on the home page, redrawn when the camera list or the drawing code changes."""
    fetch_basemap()
    newest_source = max(p.stat().st_mtime for p in (CAMS_HEADER, ROOT / "mapimage.py"))
    if not COVERAGE_IMAGE.exists() or COVERAGE_IMAGE.stat().st_mtime < newest_source:
        print("drawing the coverage map...")
        importlib.reload(mapimage)  # pick up style edits in --watch mode
        mapimage.render(cams, LAND, LAKES, BORDERS, COVERAGE_IMAGE)
    from PIL import Image
    with Image.open(COVERAGE_IMAGE) as image:
        return image.size


def load_data():
    text = CAMS_HEADER.read_text(encoding="utf-8")
    cams = [(float(lat), float(lng), int(limit), int(node)) for lat, lng, limit, node in CAM_LINE.findall(text)]
    if not cams:
        raise SystemExit(f"no cameras found in {CAMS_HEADER}")
    m = HEADER_DATE.search(text)
    updated = date(int(m.group(3)), int(m.group(2)), int(m.group(1))) if m else date.today()
    changes = json.loads(CHANGES.read_text()) if CHANGES.exists() else []
    now = datetime.now(timezone.utc)
    for change in changes:
        change["label"] = fmt_date(date.fromisoformat(change["date"]), year=False)
        change.setdefault("time", change["date"] + "T00:00:00Z")  # change logs fetched before times were kept
        change["ago"] = time_ago(datetime.fromisoformat(change["time"].replace("Z", "+00:00")), now)
    return cams, updated, changes


def time_ago(when, now):
    """'33 minutes ago', '2 days ago'. site.js redoes this in the browser so it never goes stale."""
    minutes = max(0, int((now - when).total_seconds() // 60))
    unit = lambda n, word: f"{n} {word}{'' if n == 1 else 's'} ago"
    if minutes < 1:
        return "just now"
    if minutes < 60:
        return unit(minutes, "minute")
    if minutes < 24 * 60:
        return unit(minutes // 60, "hour")
    return unit(minutes // (24 * 60), "day")


def write_cams_js(cams, updated, path):
    flat = ",".join(f"{round(lat, 5)},{round(lng, 5)},{limit},{node}" for lat, lng, limit, node in cams)
    path.write_text(
        "// generated by generate.py from the decameron firmware camera list. do not edit.\n"
        f'window.CAMS={{"updated":"{updated.isoformat()}","fields":["lat","lng","limit","osm_node"],"data":[{flat}]}};\n',
        encoding="utf-8",
    )


def fmt_date(d, year=True):
    return f"{d.day} {d.strftime('%b').lower()}" + (f" {d.year}" if year else "")


# ---------------------------------------------------------------------------
# build
# ---------------------------------------------------------------------------

env = Environment(
    loader=FileSystemLoader(TEMPLATES_DIR),
    autoescape=select_autoescape(["html"]),
    trim_blocks=True,
    lstrip_blocks=True,
    extensions=["jinja2.ext.do"],  # _faq.html collects its questions with {% do %}
)


def fail(message):
    """Stop the build from a template, e.g. when a page asks for a FAQ id that doesn't exist."""
    raise ValueError(message)


def asset(path):
    """Link to one of our own css/js files with a content stamp (style.css?v=1a2b3c4d), so a
    browser never keeps an old copy once the file has changed."""
    stamp = hashlib.sha1((ROOT / path).read_bytes()).hexdigest()[:8]
    return f"{path}?v={stamp}"


env.globals.update(fail=fail, asset=asset)


def site_base(site_url):
    """The path the site is served from, e.g. "/decameron/", taken from site_url. Only 404.html uses it:
    GitHub serves that page at whatever missing address was asked for, so its relative links need an anchor.
    A local preview (--watch) serves build/ from the root, so outside GitHub Actions it is "/"."""
    return urllib.parse.urlparse(site_url).path if os.environ.get("GITHUB_ACTIONS") else "/"


def page_urls(site_url):
    """Each page's one official address, for canonical links and sitemap.xml: the bare site address for the
    home page and no .html for the rest (GitHub Pages serves order.html at .../order, and the pages link to
    each other that way too). The 404 page has none, since it isn't a page of its own."""
    return {name: site_url + ("" if name == "index.html" else name.removesuffix(".html")) for name in PAGES if name != "404.html"}


def write_sitemap(urls, path):
    entries = "".join(f"    <url><loc>{url}</loc></url>\n" for url in urls)
    path.write_text(
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"{entries}</urlset>\n",
        encoding="utf-8",
    )


def build():
    if not (CAMS_HEADER.exists() and FIRMWARE.exists()):
        fetch()
    cams, updated, changes = load_data()

    num = len(cams)
    map_width, map_height = coverage_image(cams)
    facts = site_facts()
    site_url = facts["site_url"].rstrip("/") + "/"
    urls = page_urls(site_url)
    context = {
        **facts,
        "site_url": site_url,
        "num_cams_exact": f"{num:,}",
        "num_cams": f"{num // 1000 * 1000:,}+",
        "cams_updated": fmt_date(updated),
        "cams_updated_iso": updated.isoformat(),
        "changes": changes,
        "coverage_image": f"img/{COVERAGE_IMAGE.name}",
        "coverage_image_size": {"width": map_width, "height": map_height},
        "firmware_file": FIRMWARE_PUBLIC_NAME,
        "firmware_mb": f"{FIRMWARE.stat().st_size / 1e6:.0f}",
        "year": datetime.now().year,
        "site_base": site_base(site_url),
        "demo_video": "video/demo.mp4" if (VIDEO_DIR / "demo.mp4").exists() else None,
        "demo_poster": "video/demo.jpg" if (VIDEO_DIR / "demo.jpg").exists() else None,
    }

    shutil.rmtree(BUILD_DIR, ignore_errors=True)
    BUILD_DIR.mkdir()
    for name in PAGES:
        html = env.get_template(name).render(**context, canonical_url=urls.get(name))
        (BUILD_DIR / name).write_text(html, encoding="utf-8")
    write_sitemap(urls.values(), BUILD_DIR / "sitemap.xml")

    shutil.copytree(ROOT / "css", BUILD_DIR / "css")
    shutil.copytree(ROOT / "img", BUILD_DIR / "img")
    shutil.copytree(ROOT / "js", BUILD_DIR / "js")
    shutil.copy2(COVERAGE_IMAGE, BUILD_DIR / "img" / COVERAGE_IMAGE.name)
    if VIDEO_DIR.exists():
        shutil.copytree(VIDEO_DIR, BUILD_DIR / "video")
    write_cams_js(cams, updated, BUILD_DIR / "js" / "cams.js")
    (BUILD_DIR / "downloads").mkdir()
    shutil.copy2(FIRMWARE, BUILD_DIR / "downloads" / FIRMWARE_PUBLIC_NAME)

    print(f"built {len(PAGES)} pages · {num:,} cameras (list from {updated})")
    report()


def site_facts():
    """The facts every page shares, read from the {% set %} lines in templates/_site.html."""
    module = env.get_template("_site.html").module
    return {name: value for name, value in vars(module).items() if not name.startswith("_")}


def report():
    contact_email = site_facts()["contact_email"]
    if "example" in contact_email:
        print(f"\ncontact email is still the placeholder ({contact_email}): set it in templates/_site.html")


def watch(port):
    import livereload

    build()
    server = livereload.Server()
    server.setHeader("Cache-Control", "no-cache")  # the browser re-checks every file, so it never shows an old copy

    class PagesHandler(server.SFH):
        """Serves order.html at /order, as GitHub Pages does, so the links between pages work here too."""

        def parse_url_path(self, url_path):
            path = super().parse_url_path(url_path)
            if path and not Path(path).suffix and (Path(self.root) / f"{path}.html").is_file():
                return f"{path}.html"
            return path

    server.SFH = PagesHandler  # after setHeader, which resets it
    for path in (TEMPLATES_DIR, ROOT / "css", ROOT / "img", ROOT / "js", VIDEO_DIR, ROOT / "mapimage.py"):
        if path.exists():
            server.watch(str(path), build, delay=1.0)
    server.watch(__file__, restart, delay=1.0)
    server.serve(port=port, root=BUILD_DIR, open_url_delay=None if os.environ.get("DECAMERON_RESTARTED") else 0.5)


def restart():
    """An edited generate.py can't be reloaded in place, so the watcher restarts itself with it."""
    print("generate.py changed, restarting...")
    os.environ["DECAMERON_RESTARTED"] = "1"  # don't open another browser tab
    os.execv(sys.executable, [sys.executable, *sys.argv])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Build the site; optionally fetch fresh data, or watch and serve.")
    parser.add_argument("--fetch", action="store_true", help="download the latest camera list, firmware and change log first")
    parser.add_argument("--watch", action="store_true", help="rebuild on changes and serve build/ with live reload")
    parser.add_argument("--port", type=int, default=8000, help="port for --watch (default: 8000)")
    args = parser.parse_args()

    if args.fetch:
        fetch()
    if args.watch:
        watch(args.port)
    else:
        build()
